def emit(name, html):
    if MODE == "static":
        return  # static pages are written by emit_static
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, name), "w", encoding="utf-8").write(html)


def emit_static(name, title, body, extra_js=""):
    if MODE != "static":
        return
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, STATIC_NAMES[name]), "w", encoding="utf-8").write(page_static(title, name, body, extra_js))
